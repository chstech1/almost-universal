"""Encode the approved icon crop as a four-color LVGL indexed image."""

import argparse
from hashlib import sha256
from pathlib import Path

from PIL import Image


APPROVED_SHA = "56a3ac0cab4766aab930a9fc55076a736645a099ea97fea8ca979537a339a2a7"
CROP = (326, 178, 760, 875)
SIZE = (48, 76)
PALETTE = ((12, 21, 38), (247, 243, 233), (72, 215, 244), (129, 128, 132))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("artwork", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--preview", type=Path)
    args = parser.parse_args()
    if sha256(args.artwork.read_bytes()).hexdigest() != APPROVED_SHA:
        parser.error("expected the exact approved Almost Universal artwork")

    with Image.open(args.artwork) as source:
        image = source.convert("RGB").crop(CROP).resize(SIZE, Image.Resampling.LANCZOS)
    indices = [min(range(len(PALETTE)), key=lambda i: sum((a - b) ** 2 for a, b in zip(rgb, PALETTE[i])))
               for rgb in image.get_flattened_data()]
    data = bytearray(component for r, g, b in PALETTE for component in (b, g, r, 255))
    for first, second, third, fourth in zip(*[iter(indices)] * 4):
        data.append((first << 6) | (second << 4) | (third << 2) | fourth)

    rows = ["    " + ", ".join(f"0x{byte:02x}" for byte in data[i:i + 12]) + ","
            for i in range(0, len(data), 12)]
    args.output.write_text("/* Generated by encode_splash_icon.py from the approved image. */\n"
                           "static const uint8_t splash_icon[] = {\n" + "\n".join(rows) + "\n};\n")
    if args.preview:
        preview = Image.new("RGB", SIZE)
        preview.putdata([PALETTE[i] for i in indices])
        preview.resize((SIZE[0] * 4, SIZE[1] * 4), Image.Resampling.NEAREST).save(args.preview)


if __name__ == "__main__":
    main()
